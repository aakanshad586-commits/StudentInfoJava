package com.studentmanagement;

import com.studentmanagement.StudentDAO.Student;
import com.sun.net.httpserver.HttpExchange;
import com.sun.net.httpserver.HttpServer;
import java.io.IOException;
import java.net.InetSocketAddress;
import java.net.URLDecoder;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Pattern;

public final class LocalServer {
    private static final int MAX_FORM_BYTES = 8192;
    private static final Pattern EMAIL_PATTERN = Pattern.compile("^[^\\s@]+@[^\\s@]+\\.[^\\s@]+$");
    private final StudentDAO studentDAO = new StudentDAO();
    private final Path frontendDirectory;

    private LocalServer(Path frontendDirectory) {
        this.frontendDirectory = frontendDirectory.toAbsolutePath().normalize();
    }

    public static void main(String[] args) throws IOException, SQLException {
        Path frontend = Paths.get(args.length > 0 ? args[0] : "frontend");
        if (!Files.isDirectory(frontend)) {
            throw new IOException("Frontend directory not found: " + frontend.toAbsolutePath());
        }

        System.setProperty("STUDENT_DB_MODE", "h2");
        initializeDatabase();

        int port = Integer.parseInt(System.getenv().getOrDefault("STUDENT_PORT", "8080"));
        HttpServer server = HttpServer.create(new InetSocketAddress("127.0.0.1", port), 0);
        LocalServer application = new LocalServer(frontend);
        server.createContext("/api/students", application::handleApi);
        server.createContext("/", application::handleStaticFile);
        server.setExecutor(null);
        Runtime.getRuntime().addShutdownHook(new Thread(() -> server.stop(0)));
        server.start();
        System.out.println("Student Management is running at http://localhost:" + port + "/");
        System.out.println("Local database: " + Paths.get("data/student_management").toAbsolutePath());
        System.out.println("Press Ctrl+C to stop the server.");
    }

    private static void initializeDatabase() throws SQLException {
        String sql = "CREATE TABLE IF NOT EXISTS students ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "full_name VARCHAR(100) NOT NULL, "
                + "email VARCHAR(150) NOT NULL UNIQUE, "
                + "course VARCHAR(100) NOT NULL, "
                + "academic_year TINYINT NOT NULL CHECK (academic_year BETWEEN 1 AND 4))";
        try (Connection connection = DatabaseConnection.getConnection();
             Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    private void handleApi(HttpExchange exchange) throws IOException {
        try (ExchangeScope scope = new ExchangeScope(exchange)) {
            exchange = scope.exchange();
            if (!"/api/students".equals(exchange.getRequestURI().getPath())) {
                writeError(exchange, 404, "Endpoint not found.");
            } else if ("GET".equals(exchange.getRequestMethod())) {
                writeStudents(exchange, studentDAO.findAll());
            } else if ("POST".equals(exchange.getRequestMethod())) {
                handlePost(exchange);
            } else {
                exchange.getResponseHeaders().set("Allow", "GET, POST");
                writeError(exchange, 405, "Method not allowed.");
            }
        } catch (IllegalArgumentException exception) {
            writeError(exchange, 400, exception.getMessage());
        } catch (SQLException exception) {
            System.err.println("Student database request failed: " + exception.getMessage());
            boolean duplicate = exception.getErrorCode() == 1062
                    || (exception.getSQLState() != null && exception.getSQLState().startsWith("23"));
            writeError(exchange, duplicate ? 409 : 500, duplicate
                    ? "A student with that email address already exists."
                    : "The database request failed. Check the local database configuration.");
        }
    }

    private void handlePost(HttpExchange exchange) throws IOException, SQLException {
        byte[] body = exchange.getRequestBody().readNBytes(MAX_FORM_BYTES + 1);
        if (body.length > MAX_FORM_BYTES) {
            writeError(exchange, 413, "Form submission is too large.");
            return;
        }
        Map<String, String> form = parseForm(new String(body, StandardCharsets.UTF_8));
        String action = required(form, "action");
        switch (action) {
            case "add":
                studentDAO.create(readStudent(form, 0));
                writeMessage(exchange, 201, "Student added.");
                break;
            case "update":
                if (!studentDAO.update(readStudent(form, parseId(form)))) {
                    writeError(exchange, 404, "Student record not found.");
                    return;
                }
                writeMessage(exchange, 200, "Student updated.");
                break;
            case "delete":
                if (!studentDAO.delete(parseId(form))) {
                    writeError(exchange, 404, "Student record not found.");
                    return;
                }
                writeMessage(exchange, 200, "Student deleted.");
                break;
            default:
                throw new IllegalArgumentException("Choose a valid student action.");
        }
    }

    private static Student readStudent(Map<String, String> form, long id) {
        String fullName = required(form, "fullName");
        String email = required(form, "email");
        String course = required(form, "course");
        String yearValue = required(form, "year");
        if (fullName.length() > 100 || email.length() > 150 || course.length() > 100) {
            throw new IllegalArgumentException("Name, email, or course exceeds the allowed length.");
        }
        if (!EMAIL_PATTERN.matcher(email).matches()) {
            throw new IllegalArgumentException("Enter a valid email address.");
        }

        int year;
        try {
            year = Integer.parseInt(yearValue);
        } catch (NumberFormatException exception) {
            throw new IllegalArgumentException("Choose an academic year from 1 to 4.");
        }
        if (year < 1 || year > 4) {
            throw new IllegalArgumentException("Choose an academic year from 1 to 4.");
        }
        return new Student(id, fullName, email, course, year);
    }

    private static long parseId(Map<String, String> form) {
        try {
            long id = Long.parseLong(required(form, "id"));
            if (id < 1) throw new NumberFormatException();
            return id;
        } catch (NumberFormatException exception) {
            throw new IllegalArgumentException("A valid student ID is required.");
        }
    }

    private static Map<String, String> parseForm(String body) {
        Map<String, String> values = new HashMap<>();
        if (body.isEmpty()) return values;
        for (String pair : body.split("&")) {
            int separator = pair.indexOf('=');
            String key = decode(separator < 0 ? pair : pair.substring(0, separator));
            String value = decode(separator < 0 ? "" : pair.substring(separator + 1));
            if (values.putIfAbsent(key, value) != null) {
                throw new IllegalArgumentException("Duplicate form field: " + key);
            }
        }
        return values;
    }

    private static String decode(String value) {
        return URLDecoder.decode(value, StandardCharsets.UTF_8);
    }

    private static String required(Map<String, String> values, String name) {
        String value = values.get(name);
        if (value == null || value.trim().isEmpty()) {
            throw new IllegalArgumentException("Please provide " + name + ".");
        }
        return value.trim();
    }

    private static void writeStudents(HttpExchange exchange, List<Student> students) throws IOException {
        StringBuilder json = new StringBuilder("{\"students\":[");
        for (int index = 0; index < students.size(); index++) {
            if (index > 0) json.append(',');
            Student student = students.get(index);
            json.append("{\"id\":").append(student.getId())
                    .append(",\"fullName\":").append(jsonString(student.getFullName()))
                    .append(",\"email\":").append(jsonString(student.getEmail()))
                    .append(",\"course\":").append(jsonString(student.getCourse()))
                    .append(",\"year\":").append(student.getYear()).append('}');
        }
        json.append("]}");
        writeJson(exchange, 200, json.toString());
    }

    private static void writeMessage(HttpExchange exchange, int status, String message) throws IOException {
        writeJson(exchange, status, "{\"message\":" + jsonString(message) + "}");
    }

    private static void writeError(HttpExchange exchange, int status, String message) throws IOException {
        writeJson(exchange, status, "{\"error\":" + jsonString(message) + "}");
    }

    private static void writeJson(HttpExchange exchange, int status, String json) throws IOException {
        byte[] body = json.getBytes(StandardCharsets.UTF_8);
        exchange.getResponseHeaders().set("Content-Type", "application/json; charset=UTF-8");
        exchange.getResponseHeaders().set("Cache-Control", "no-store");
        exchange.sendResponseHeaders(status, body.length);
        exchange.getResponseBody().write(body);
    }

    private void handleStaticFile(HttpExchange exchange) throws IOException {
        try (ExchangeScope scope = new ExchangeScope(exchange)) {
            exchange = scope.exchange();
            String requestPath = URLDecoder.decode(exchange.getRequestURI().getRawPath(), StandardCharsets.UTF_8);
            String relativePath = "/".equals(requestPath) ? "index.html" : requestPath.substring(1);
            Path file = frontendDirectory.resolve(relativePath).normalize();
            if (!file.startsWith(frontendDirectory) || !Files.isRegularFile(file)) {
                writeText(exchange, 404, "Not found.");
                return;
            }

            String contentType;
            String filename = file.getFileName().toString();
            if (filename.endsWith(".html")) contentType = "text/html; charset=UTF-8";
            else if (filename.endsWith(".css")) contentType = "text/css; charset=UTF-8";
            else if (filename.endsWith(".js")) contentType = "text/javascript; charset=UTF-8";
            else {
                writeText(exchange, 404, "Not found.");
                return;
            }

            byte[] content = Files.readAllBytes(file);
            exchange.getResponseHeaders().set("Content-Type", contentType);
            exchange.getResponseHeaders().set("Cache-Control", "no-store");
            exchange.sendResponseHeaders(200, content.length);
            exchange.getResponseBody().write(content);
        } catch (IllegalArgumentException exception) {
            writeText(exchange, 400, "Invalid path.");
        }
    }

    private static void writeText(HttpExchange exchange, int status, String text) throws IOException {
        byte[] body = text.getBytes(StandardCharsets.UTF_8);
        exchange.getResponseHeaders().set("Content-Type", "text/plain; charset=UTF-8");
        exchange.sendResponseHeaders(status, body.length);
        exchange.getResponseBody().write(body);
    }

    private static final class ExchangeScope implements AutoCloseable {
        private final HttpExchange exchange;

        private ExchangeScope(HttpExchange exchange) {
            this.exchange = exchange;
        }

        private HttpExchange exchange() {
            return exchange;
        }

        @Override
        public void close() {
            exchange.close();
        }
    }

    private static String jsonString(String value) {
        StringBuilder escaped = new StringBuilder("\"");
        for (int index = 0; index < value.length(); index++) {
            char character = value.charAt(index);
            switch (character) {
                case '"': escaped.append("\\\""); break;
                case '\\': escaped.append("\\\\"); break;
                case '\b': escaped.append("\\b"); break;
                case '\f': escaped.append("\\f"); break;
                case '\n': escaped.append("\\n"); break;
                case '\r': escaped.append("\\r"); break;
                case '\t': escaped.append("\\t"); break;
                default:
                    if (character < 0x20) {
                        escaped.append(String.format("\\u%04x", (int) character));
                    } else {
                        escaped.append(character);
                    }
            }
        }
        return escaped.append('"').toString();
    }
}
